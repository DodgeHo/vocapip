def validate(pack=PACK,hashes=True):
 err=[]; req={"manifest.json","records.jsonl","content.sqlite","source-lock.json","content-report.json","LICENSES.md","THIRD_PARTY_NOTICES.md","SHA256SUMS"}; miss=sorted(x for x in req if not (pack/x).is_file())
