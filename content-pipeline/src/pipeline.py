 if pos=="noun":
  good=bool(re.search(r"\b"+det+r"\s+(?:[a-z]+\s+){0,2}"+w+r"\b",low) or re.search(r"\b"+w+r"\s+(?:is|was|has|of|for|with)\b",low))
  bad=bool(re.search(r"\b"+modal+r"\s+"+w+r"\b",low))
 elif pos=="verb":
  good=bool(re.search(r"\b"+modal+r"(?:\s+[a-z]+){0,2}\s+"+w+r"\b",low) or re.search(r"\b(?:i|you|we|they|he|she|it|tom|mary)\s+(?:never\s+|always\s+|usually\s+)?"+w+r"\b",low))
  bad=bool(re.search(r"\b"+det+r"\s+"+w+r"\b",low))
 elif pos=="adjective":
  good=bool(re.search(r"\b"+w+r"\s+[a-z]+\b",low) or re.search(r"\b(?:be|am|is|are|was|were|seem|seems|look|looks|feel|feels|very|too|so)\s+"+w+r"\b",low))
  bad=False
 else:
  good=True; bad=False
 return 0 if good and not bad else (2 if bad else 1)

