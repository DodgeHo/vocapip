def toks(s): return {x for x in re.findall(r"[a-z]+",s.lower()) if len(x)>2 and x not in {"the","and","for","that","with","from","into","one","someone","something"}}
def sim(a,b):
 x,y=toks(a),toks(b)
 return len(x&y)/len(x|y) if x and y else 0.0

class Oewn:
 def __init__(self):
  self.entries={}; self.cache={}
  with zipfile.ZipFile(OEWN) as z:
   for n in z.namelist():
    if n.startswith("entries-") and n.endswith(".json"): self.entries.update(json.loads(z.read(n)))
 def senses(self,w,pos): return self.entries.get(w,{}).get(POS_CODE[pos],{}).get("sense",[])
 def syn(self,sid):
  code=sid[-1]
  if code=="s": code="a"
  if code not in self.cache:
   merged={}
   prefix=POS_FILE[code]+"."
   with zipfile.ZipFile(OEWN) as z:
    for name in z.namelist():
     if name.startswith(prefix) and name.endswith(".json"): merged.update(json.loads(z.read(name)))
   self.cache[code]=merged
  return self.cache[code][sid]
 def verify(self,w,pos,sid):
  if sid not in {x["synset"] for x in self.senses(w,pos)}: raise ValueError("OEWN lemma/POS/synset mismatch")
  s=self.syn(sid)
  if w.lower() not in {x.replace("_"," ").lower() for x in s.get("members",[])}: raise ValueError("OEWN member mismatch")
  return s
 def choose(self,w,pos,sense):
  vals=[]
  for i,x in enumerate(self.senses(w,pos)):
   s=self.syn(x["synset"]); definition=" ".join(s.get("definition",[])); vals.append((sim(definition,sense),-i,x["synset"],s))
  if not vals: raise ValueError("no OEWN sense")
  _,_,sid,s=max(vals); return sid,s

