  with bz2.open(VENDOR/TF[key],"rt",encoding="utf-8") as f:
   for line in f:
    p=line.rstrip("\n").split("\t")
    if p and p[0].isdigit() and int(p[0]) in want:
     s=sent(p,zero)
     if s: target[s.id]=s
